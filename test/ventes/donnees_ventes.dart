/// Ligne JSON telle que renvoyée par la vue v_commandes.
Map<String, dynamic> ligneVCommandes({
  String id = 'c1',
  String type = 'vente',
  String? clientNom = 'Maman Rose',
  String statutLivraison = 'livree',
  String statutPaiement = 'partiellement_payee',
  num total = 22000,
  num paye = 14000,
  num frais = 0,
  String date = '2026-11-18',
  String? dateLivraison,
  String? modeRemise,
  List<Map<String, Object>>? articles,
}) =>
    {
      'id': id,
      'type': type,
      'client_id': clientNom == null ? null : 'cl-$clientNom',
      'client_nom': clientNom,
      'client_telephone': '+243 99 000 0000',
      'date_commande': date,
      'statut_livraison': statutLivraison,
      'note': null,
      'nb_pieces': 2,
      'total': total,
      'total_articles': total - frais,
      'frais_livraison': frais,
      'cout': 16000,
      'benefice': total - frais - 16000,
      'gain_au_dessus': 0,
      'cout_remises': 2000,
      'total_paye': paye,
      'reste_a_payer': statutLivraison == 'annulee' ? 0 : (total - paye).clamp(0, total),
      'statut_paiement': statutPaiement,
      'created_at': '${date}T09:30:00Z',
      'date_livraison': dateLivraison,
      'mode_remise': modeRemise,
      'adresse_livraison': modeRemise == 'livraison' ? 'Av. du Commerce 12' : null,
      // Absente avant la mise à jour SQL du 21/11 : l'appli doit s'en passer.
      'articles_resume': ?articles,
    };
